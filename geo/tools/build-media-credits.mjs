// Generate the clue image maps and individual credit pages from reviewed selections.
import {readFileSync,writeFileSync} from 'node:fs';

const read = path => JSON.parse(readFileSync(new URL(path,import.meta.url),'utf8'));
const rows = read('../data/clue-photos.json');
const esc = s => String(s || '').replace(/\s+/g,' ').trim().replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
const link = (url,label) => /^https:\/\//.test(url || '')
  ? `<a href="${esc(url)}" rel="noopener noreferrer">${esc(label)}</a>`
  : esc(label);
const credits = {};
const foods = {};
const people = {};
const depictions = {};
const articles = rows.map(row => {
  const {id,kind,key,asset,file,author,sourcePage,license,licenseUrl,credit,attribution,copyright,depiction,cropped} = row;
  credits[asset] = id;
  (kind === 'food' ? foods : people)[key] = asset;
  if(kind === 'person' && row.depictionType)depictions[key]=row.depictionType;
  const changes = cropped
    ? 'Кадрировано, уменьшено и переведено в WebP. / Cropped, resized and converted to WebP.'
    : 'Уменьшено и переведено в WebP. / Resized and converted to WebP.';
  return `<article id="${id}"><h2>${esc(file)}</h2>
<p>Автор / Creator: ${esc(author)}</p>
<p>${link(sourcePage,'Оригинальная страница файла / Original file page')}</p>
${credit ? `<p>Источник / Credit: ${esc(credit)}</p>\n` : ''}${attribution ? `<p>Указание правообладателя / Attribution notice: ${esc(attribution)}</p>\n` : ''}<p>Лицензия / License: ${link(licenseUrl,license)}</p>
${copyright ? `<p>${esc(copyright)}</p>\n` : ''}${depiction ? `<p>${esc(depiction)}</p>\n` : ''}<p>Изменения / Changes: ${changes}</p>
${license.startsWith('CC BY-SA') ? `<p>Копия распространяется на условиях ${link(licenseUrl,license)}. / This copy is shared under ${link(licenseUrl,license)}.</p>\n` : ''}</article>`;
});
credits['assets/banknotes/EUR-ecb-72dpi.jpg'] = 'ecb';
articles.push('<article id="ecb"><h2>Образец банкноты / Specimen banknote</h2><p>© European Central Bank (ECB).</p><p><a href="https://www.ecb.europa.eu/euro/banknotes/images/html/index.en.html">Источник и правила воспроизведения / Source and reproduction rules</a></p><p>Официальное изображение 72 dpi с маркировкой specimen. Файл не изменён; в игре масштабируется для экрана. / Official 72 dpi specimen image. The file is unchanged; scaled for screen display in the game.</p></article>');
credits['assets/banknotes/sterling-detail.webp'] = 'sterling';
articles.push('<article id="sterling"><h2>Фрагмент банкноты / Banknote detail</h2><p>© Bank of England.</p><p><a href="https://www.flickr.com/photos/bankofengland/48874740572/in/album-72157662787666013">Источник / Source</a></p><p><a href="https://www.bankofengland.co.uk/banknotes/using-images-of-banknotes">Правила воспроизведения / Reproduction rules</a></p><p>Фрагмент оборотной стороны полимерной банкноты £20, менее 50% одной стороны по условию 5(c). Кадрировано и переведено в WebP. / Detail from the reverse of the £20 polymer note, below 50% of one side under condition 5(c). Cropped and converted to WebP.</p></article>');

const write = (path,value) => writeFileSync(new URL(path,import.meta.url),value);
const json = value => JSON.stringify(value,null,2);
const generated = '// Generated by tools/build-media-credits.mjs from data/clue-photos.json.\n';
write('../photos.js', `${generated}export const PHOTOS = ${json(foods)};\nexport const PERSON_PHOTOS = ${json(people)};\nexport const PERSON_DEPICTIONS = ${json(depictions)};\n`);
write('../media-credits.js', `${generated}export const PHOTO_CREDITS = ${json(credits)};\n`);
write('../credits.html', `<!doctype html><html lang="ru"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Фото: автор и лицензия / Photo credits</title>
<style>body{max-width:800px;margin:32px auto;padding:0 20px;font:16px/1.6 system-ui,sans-serif;color:#3f2b1c;background:#f0e2c5}a{color:#743422;overflow-wrap:anywhere}article{display:none}article:target{display:block}h2{overflow-wrap:anywhere}p{white-space:normal;overflow-wrap:anywhere}</style>
<h1>Фото: автор и лицензия / Photo credits</h1>
${articles.join('\n')}\n</html>\n`);
console.log(`Built ${rows.length} clue image attributions`);
